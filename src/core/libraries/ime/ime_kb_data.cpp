const ImeKbPageData* GetImeKeyboardPageData(ImeKbVariant variant, OrbisImeType type,
                                            ImeKbPage page) {
    const auto language = static_cast<std::size_t>(variant);
    if (language == 0 || language > kPageMap.size() / kInputModeCount) {
        return nullptr;
    }
    const u32 mode = static_cast<u32>(type);
    const std::size_t mode_index = mode <= 4                                ? mode
                                   : type == OrbisImeType::SocialName       ? 5
                                   : type == OrbisImeType::FacebookPassword ? 6
                                                                            : 0;
    const auto index = static_cast<std::size_t>(page);
    if (index >= kPageMap.front().size()) {
        return nullptr;
    }
    const auto id = kPageMap[(language - 1) * kInputModeCount + mode_index][index];
    return id ? &kPages[id - 1] : nullptr;
}

const ImeKbCharacter& GetImeKeyboardCharacter(u16 index) {
    return kCharacters[index];
}

void AddImeKeyboardDataGlyphs(ImFontGlyphRangesBuilder& builder) {
    for (const auto& character : kCharacters) {
        builder.AddText(character.text);
        builder.AddText(character.label);
    }
}

